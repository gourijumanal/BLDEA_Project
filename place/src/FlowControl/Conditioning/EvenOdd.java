package FlowControl.Conditioning;

public class EvenOdd {
    public static void main(String[] args) {
        int n;
        n=25;

        if (n % 2 == 0) {
            System.out.println(n + " is an even number.");
        } else {
            System.out.println(n + " is an odd number.");
        }
    }
}
